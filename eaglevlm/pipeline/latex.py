"""LaTeX tables for the paper, built only from the pipeline's summary rows (called by eaglevlm.pipeline.tables when the
tables config has latex_dir).  Every cell is the mean over the general VLM judges; the per-judge numbers are in the
markdown tables and the supplement.  '--' = no output in any split; blank = not run."""
import math, os

GEN_DEF = ["qwen3vl8b", "internvl35_8b", "qwen35_9b", "qwen25vl7b", "qwen3vl32b", "internvl35_38b"]


def _m(rows, k):
    v = [r[k] for r in rows if isinstance(r.get(k), float) and r[k] == r[k]]
    return sum(v) / len(v) if v else float("nan")


def _f(v, d=2):
    return "--" if v != v else f"{v:.{d}f}"


def write(cfg, CONV, CERT, ROUT, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    GEN = cfg["general_judges"]; SN = cfg.get("latex_names", cfg["dataset_names"]); stamp = cfg.get("_stamp", "")
    head = f"% generated by eaglevlm.pipeline.tables from summary CSVs {stamp}; do not edit by hand\n"
    sets = [s for s in cfg["dataset_order"] if any((s, j) in CONV for j in GEN)]
    # ---- datasets
    L = [head, "\\begin{tabular}{llrr}", "\\toprule", "Benchmark & Task & Pairs & Human ties \\\\", "\\midrule"]
    for s in sets:
        r = next(CONV[(s, j)] for j in GEN if (s, j) in CONV)
        L.append(f"{SN[s]} & {cfg['latex_tasks'].get(s, '')} & {int(r['n']):,} & {r['human_tie']:.2f} \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]; open(f"{out_dir}/tab_datasets.tex", "w").write("\n".join(L) + "\n")
    # ---- accuracy / calibration with and without ties
    K = [("judge_tie_share", 3), ("acc_ties_dropped", 2), ("acc_ties_wrong", 2), ("ece_ties_dropped", 2), ("ece_ties_kept", 2),
         ("err_auroc_ties_dropped", 2), ("err_auroc_ties_kept", 2), ("aurc_ties_dropped", 2), ("aurc_ties_kept", 2)]
    L = [head, "\\begin{tabular}{l rr rr rr rr rr}", "\\toprule",
         " & \\multicolumn{2}{c}{Tie rate} & \\multicolumn{2}{c}{Accuracy} & \\multicolumn{2}{c}{ECE $\\downarrow$} & \\multicolumn{2}{c}{AUROC} & \\multicolumn{2}{c}{AURC $\\downarrow$} \\\\",
         "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\\cmidrule(lr){8-9}\\cmidrule(lr){10-11}",
         "Benchmark & human & judge & w/o ties & w/ ties & w/o & w/ & w/o & w/ & w/o & w/ \\\\", "\\midrule"]
    for s in sets:
        rs = [CONV[(s, j)] for j in GEN if (s, j) in CONV]
        L.append(f"{SN[s]} & {_f(rs[0]['human_tie'])} & " + " & ".join(_f(_m(rs, k), d) for k, d in K) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]; open(f"{out_dir}/tab_inflation.tex", "w").write("\n".join(L) + "\n")
    # ---- certification at alpha = cfg latex_alpha (main and full)
    al = cfg.get("latex_alpha", 0.2)
    M = cfg["latex_methods"]           # [[code, label], ...]
    cols = [("acceptance", "Cov.", 2), ("decisive", "Dec.", 2), ("set_size", "Size", 2), ("risk", "Risk", 3), ("guarantee_success", "GS", 2),
            ("significant_violation", "Sig.", 2)]
    for name, dsets in (("tab_certify_main", cfg["latex_main_sets"]), ("tab_certify_full", sets)):
        L = [head, "\\begin{tabular}{ll" + "r" * len(cols) + "}", "\\toprule",
             "Benchmark & Method & " + " & ".join(c for _, c, _ in cols) + " \\\\", "\\midrule"]
        for s in dsets:
            first = True
            for code, lab in M:
                rs = [CERT[(s, j, code, al)] for j in GEN if (s, j, code, al) in CERT]
                if not rs:
                    continue
                cells = []
                for k, _, d in cols:
                    v = _m(rs, k)
                    if k == "risk" and v == v and v > al + 1e-9:
                        cells.append(f"\\textcolor{{red}}{{{_f(v, d)}}}")
                    elif k == "guarantee_success" and v == v and v < 0.9 - 1e-9:
                        cells.append(f"\\textcolor{{red}}{{{_f(v, d)}}}")
                    else:
                        cells.append(_f(v, d))
                L.append(f"{SN[s] if first else ''} & {lab} & " + " & ".join(cells) + " \\\\")
                first = False
            L.append("\\midrule")
        L[-1] = "\\bottomrule"; L.append("\\end{tabular}"); open(f"{out_dir}/{name}.tex", "w").write("\n".join(L) + "\n")
    # ---- router
    V = cfg["latex_router_variants"]; rcols = [("acceptance", "Cov."), ("informative", "Inf."), ("level_precision", "Lvl.prec"), ("risk", "Risk")]
    L = [head, "\\begin{tabular}{l" + "rr" * len(V) + "rr}", "\\toprule",
         "Benchmark & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{lab}}}" for _, lab in V) + " & \\multicolumn{2}{c}{Router} \\\\",
         " & " + " & ".join("Cov. & Inf." for _ in V) + " & Lvl.prec & Risk \\\\", "\\midrule"]
    for s in cfg["router_datasets"]:
        cells = []
        for v, _ in V:
            rs = [ROUT[(s, j, v, "overall", al)] for j in GEN if (s, j, v, "overall", al) in ROUT]
            cells += [_f(_m(rs, "acceptance")), _f(_m(rs, "informative"))]
        rs = [ROUT[(s, j, "router: cells", "overall", al)] for j in GEN if (s, j, "router: cells", "overall", al) in ROUT]
        if not rs:
            continue
        cells += [_f(_m(rs, "level_precision")), _f(_m(rs, "risk"), 3)]
        L.append(f"{SN[s]} & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]; open(f"{out_dir}/tab_router.tex", "w").write("\n".join(L) + "\n")
    return sorted(os.listdir(out_dir))
