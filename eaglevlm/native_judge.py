"""Native-protocol runs of dedicated multimodal judge / reward models (generation with vLLM).
Prompts are copied from the official inference code:
  r1reward       R1-Reward (yfzhang114/r1_reward, inference/VL-Reward-Bench/r1_reward.py): <think>..</think><answer>1|2</answer>,
                 ties not allowed; max_pixels = 1003520 // 2 as in the official script.
  llavacritic7b  LLaVA-Critic pairwise ranking prompt (model card, lmms-lab/llava-critic-7b): free-text critique.
  mmrlhf_critic  MM-RLHF-Reward step 1 (inference/Multimodal-Reward/get_mm-rlhf_reward.py): greedy critique of ONE response;
                 the scalar reward head is applied afterwards by mmrlhf_score.py.
Per pair and order (AB = cand0 first): one greedy generation (the official decoding) plus --n samples at temperature 1
(vote-based confidence, as in R1-Reward's Voting@K). Response-judging items only (text candidates about an image).
Output rows: {id, model, order, greedy: text, samples: [text], parsed: {greedy: 1|2|T|None, samples: [...]}}
  (for mmrlhf_critic: {id, model, cand: 0|1, critique: text, prompt: text})
usage (vllm env): python native_judge.py --model r1reward --model-path P --items a.jsonl,b.jsonl --out DIR [--n 5]"""
import argparse, json, os, re, sys, zlib
from PIL import Image

ap = argparse.ArgumentParser()
ap.add_argument("--model", required=True, choices=["r1reward", "llavacritic7b", "mmrlhf_critic"])
ap.add_argument("--model-path", required=True)
ap.add_argument("--items", required=True)
ap.add_argument("--out", required=True)
ap.add_argument("--n", type=int, default=5)
ap.add_argument("--max-tokens", type=int, default=2048)
ap.add_argument("--gpu-mem", type=float, default=0.45)
ap.add_argument("--limit", type=int, default=0)
ap.add_argument("--chunk", type=int, default=64, help="pairs per vLLM call (results are flushed per chunk)")
a = ap.parse_args()
ROOT = os.environ.get("EAGLEVLM_DATA", os.getcwd())
MAXCHARS = 4000

R1 = ("You are a highly skilled and impartial evaluator tasked with comparing two responses generated by a Large Multimodal Model for a given question. "
      "- Start with a thorough, side-by-side comparative analysis enclosed within <think> and </think> tags. A tie is not permitted; you must choose a better option.\n\n"
      "- Conclude with a single numeric choice enclosed within <answer> and </answer> tags:\n"
      "  - Output \"1\" if Response 1 is better.\n"
      "  - Output \"2\" if Response 2 is better.\n\n"
      "###### **Input:**  \n"
      "###### [Question]:\n{question}  \n\n"
      "###### [Response 1]:\n{answer1}  \n\n"
      "###### [Response 2]:\n{answer2}  \n\n"
      "###### **Output Format (strictly follow):**  \n"
      "<think>Your detailed comparative analysis goes here</think><answer>1/2</answer>")
CRITIC = ("Given an image and a corresponding question, please serve as an unbiased and fair judge to evaluate the quality of "
          "the answers provided by a Large Multimodal Model (LMM). Determine which answer is better and explain your reasoning "
          "with specific details. Your task is provided as follows:\nQuestion: [{question}]\nThe first response: [{answer1}]\n"
          "The second response: [{answer2}]\nASSISTANT:\n")
MMRLHF = ("You are an unbiased and fair evaluator tasked with assessing the quality of answers provided by a Large Multimodal Model (LMM). "
          "Given the following question and the LMM's response, please evaluate the correctness, clarity, and completeness of the answer. "
          "Provide a detailed explanation of your assessment, including specific points of strength and areas for improvement.\n\n"
          "[Question]: {question}\n"
          "[LMM Response]: {answer}\n\n"
          "[Evaluation]:")


def clip(t):
    t = t or ""
    return t if len(t) <= MAXCHARS else t[:MAXCHARS] + " ...[truncated]"


def parse(model, text):
    if model == "r1reward":
        m = re.search(r"<answer>(.*?)</answer>", text, re.DOTALL)
        s = m.group(1) if m else text
        d = re.findall(r"[12]", s)
        return d[-1] if d else None
    t = text.lower()                                   # LLaVA-Critic: fixed closing line, else heuristics
    m = re.findall(r"the better (?:response|answer)\s*:\s*\[?\s*(first|second)", t)
    if m:
        return "1" if m[-1] == "first" else "2"
    if re.search(r"two (?:responses|answers) are equally good", t):
        return "T"
    tail = t[-400:]
    if re.search(r"equally good|equally (?:helpful|accurate|valid)|both responses are equally|tie\b", tail):
        return "T"
    sents = [s for s in re.split(r"(?<=[.!?])\s+", t) if re.search(r"better|prefer|superior|more accurate|more helpful|wins", s)]
    for s in reversed(sents):
        f, g = s.find("first"), s.find("second")
        if f >= 0 and (g < 0 or f < g):
            return "1"
        if g >= 0:
            return "2"
    return None


items = [json.loads(l) for f in a.items.split(",") for l in open(f)]
items = [r for r in items if r["kind"] == "resp" and r.get("context")]
if a.limit:
    items = items[: a.limit]
os.makedirs(a.out, exist_ok=True)
outp = os.path.join(a.out, f"{a.model}.jsonl")
done = set()
if os.path.exists(outp):
    for l in open(outp):
        x = json.loads(l); done.add((x["id"], x.get("order", x.get("cand"))))

import numpy as _np                      # vllm_g4 ships a scipy that still references np.long (removed in numpy 2);
if not hasattr(_np, "long"):              # alias at runtime instead of touching the environment
    _np.long = _np.int64; _np.ulong = _np.uint64
from vllm import LLM, SamplingParams
kw = dict(model=a.model_path, gpu_memory_utilization=a.gpu_mem, max_model_len=16384, limit_mm_per_prompt={"image": max(len(r["context"]) for r in items)},
          trust_remote_code=False, seed=0)
if a.model == "r1reward":
    kw["mm_processor_kwargs"] = {"max_pixels": 1003520 // 2}
llm = LLM(**kw)
greedy = SamplingParams(temperature=0, max_tokens=a.max_tokens)
samp = SamplingParams(temperature=1.0, top_p=1.0, max_tokens=a.max_tokens, n=a.n, seed=0)


def msgs(r, text):
    c = []
    for p in r["context"]:
        im = Image.open(os.path.join(ROOT, p)).convert("RGB")
        c.append({"type": "image_pil", "image_pil": im})
    c.append({"type": "text", "text": text})
    return [{"role": "user", "content": c}]


jobs = []
for r in items:
    q = clip(r["question"]); c0, c1 = clip(r["cand"][0]), clip(r["cand"][1])
    if a.model == "mmrlhf_critic":
        for k, ans in enumerate((c0, c1)):
            if (r["id"], k) not in done:
                jobs.append((r, k, MMRLHF.format(question=q, answer=ans)))
    else:
        T = R1 if a.model == "r1reward" else CRITIC
        for order, (x, y) in (("AB", (c0, c1)), ("BA", (c1, c0))):
            if (r["id"], order) not in done:
                jobs.append((r, order, T.format(question=q, answer1=x, answer2=y)))
print(f"{len(jobs)} jobs ({len(done)} done)", flush=True)
f = open(outp, "a")
for s in range(0, len(jobs), a.chunk):
    J = jobs[s: s + a.chunk]
    M = [msgs(r, t) for r, _, t in J]
    G = llm.chat(M, greedy, use_tqdm=False)
    S = llm.chat(M, samp, use_tqdm=False) if a.model != "mmrlhf_critic" else None
    for i, (r, key, t) in enumerate(J):
        g = G[i].outputs[0].text
        if a.model == "mmrlhf_critic":
            row = {"id": r["id"], "model": a.model, "cand": key, "prompt": t, "critique": g,
                   "finish": G[i].outputs[0].finish_reason}
        else:
            ss = [o.text for o in S[i].outputs]
            row = {"id": r["id"], "model": a.model, "order": key, "greedy": g, "samples": ss,
                   "parsed": {"greedy": parse(a.model, g), "samples": [parse(a.model, x) for x in ss]},
                   "finish": [G[i].outputs[0].finish_reason] + [o.finish_reason for o in S[i].outputs]}
        f.write(json.dumps(row) + "\n")
    f.flush()
    print(f"{min(s + a.chunk, len(jobs))}/{len(jobs)}", flush=True)
print("DONE", flush=True)
