"""Routing table of the supplement (2026-11-09; exploratory follow-up of E2, after the pre-registered results): correct
automated decisions per 100 sources (alpha = .2, overall certificate, mean over judges) when a pairwise judge is in place
and part of the pairs get pointwise scores, chosen by tie probability, by pairwise action uncertainty or at random; with the
endpoints (pairwise only, both on every pair) and pointwise only as a reference.  Source:
results/e2_cost/20261109_routing_followup/e2_summary.csv (scripts/e2_cost.py --followup).
usage (repo root): python paper_figures/make_routing_table.py --out <paper folder>/tables/tab_routing.tex"""
import argparse, csv
RES = "/media/shawn/C/papers/VLM/results/e2_cost/20261109_routing_followup/e2_summary.csv"
COLS = [("mllm_judge_sp", "mid"), ("mllm_judge_sp", "high"), ("genaibench", "mid"), ("genaibench", "high"),
        ("imagenhub/edit", "mid"), ("imagenhub/edit", "high")]
ap = argparse.ArgumentParser(); ap.add_argument("--out", required=True); a = ap.parse_args()
T = {(r["dataset"], r["tau"], r["policy"]): r for r in csv.DictReader(open(RES)) if r["cert"] == "all" and abs(float(r["alpha"]) - .2) < 1e-9}
c = lambda ds, t, p: float(T[(ds, t, p)]["correct"])
calls = lambda p: sum(float(T[(ds, t, p)]["calls"]) for ds, t in COLS) / len(COLS)
L = ["% generated by paper_figures/make_routing_table.py from results/e2_cost/20261109_routing_followup; do not edit by hand", "",
     r"\begin{tabular}{llrrrrrrr}", r"\toprule",
     r" & & & \multicolumn{2}{c}{MLLM-J (scores)} & \multicolumn{2}{c}{GenAI-Bench} & \multicolumn{2}{c}{ImagenHub edit} \\",
     r"\cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}",
     r"Policy & Scored pairs chosen by & Calls & mid & high & mid & high & mid & high \\", r"\midrule",
     "Pairwise only & -- & %.1f & " % calls("pair") + " & ".join("%.1f" % c(ds, t, "pair") for ds, t in COLS) + r" \\"]
for fr, lab in (("0.1", "10\\%"), ("0.25", "25\\%"), ("0.5", "50\\%")):
    L.append(r"\addlinespace")
    vals = {g: [c(ds, t, f"cts:{g}@{fr}") for ds, t in COLS] for g in ("tie", "qunc", "random")}
    for g, name in (("tie", "tie probability"), ("qunc", "pairwise uncertainty"), ("random", "at random")):
        cells = []
        for k in range(len(COLS)):
            v = vals[g][k]; best = max(vals[x][k] for x in vals)
            cells.append(("\\textbf{%.1f}" % v) if abs(v - best) < 1e-9 else "%.1f" % v)
        first = ("+ score %s of the pairs" % lab) if g == "tie" else ""
        L.append(f"{first} & {name} & {calls(f'cts:{g}@{fr}'):.1f} & " + " & ".join(cells) + r" \\")
L += [r"\addlinespace", "Both on every pair & -- & %.1f & " % calls("both") + " & ".join("%.1f" % c(ds, t, "both") for ds, t in COLS) + r" \\",
      r"\midrule",
      "Pointwise only & -- & %.1f & " % calls("pw") + " & ".join("%.1f" % c(ds, t, "pw") for ds, t in COLS) + r" \\",
      f"Score first, compare 75\\% & pointwise uncertainty & {calls('stc:punc@0.75'):.1f} & " + " & ".join("%.1f" % c(ds, t, "stc:punc@0.75") for ds, t in COLS) + r" \\",
      r"\bottomrule", r"\end{tabular}"]
open(a.out, "w").write("\n".join(L) + "\n"); print("\n".join(L))
