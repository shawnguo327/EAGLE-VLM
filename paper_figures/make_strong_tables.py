def tab_absolute(out):
    """Ship, reject or escalate on one metric: correct automated decisions per 100 sources (automated share in brackets)."""
    R = [r for r in rows(f"{RES}/absolute_actions/20261108_sw/absolute_actions_summary.csv") if A2(r) and r["cert"] == "all"]
    D = {(r["dataset"], r["tau"], r["policy"]): r for r in R}
    AR = {(r["dataset"], r["tau"]): r for r in rows(f"{RES}/always_reject_matched/20261108/always_reject_matched_summary.csv") if A2(r)}
    COLS = [("mllm_judge_sp", "mid"), ("mllm_judge_sp", "high"), ("genaibench", "mid"), ("genaibench", "high"), ("imagenhub/edit", "mid"), ("imagenhub/edit", "high")]
    POL = [("Pairwise, ship only", "pair|h4|ship", 4), ("Pairwise, ship or reject", "pair|h4|sr", 4), ("Pointwise, ship or reject", "pw|h4|sr", 2),
           ("Pointwise, per-candidate head", "pw|ind|sr", 2), ("Pairwise + pointwise", "both|h4|sr", 6)]
    L = [r"\begin{tabular}{lrrrrrrr}", r"\toprule",
         r" & & \multicolumn{2}{c}{MLLM-J (scores)} & \multicolumn{2}{c}{GenAI-Bench} & \multicolumn{2}{c}{ImagenHub edit} \\",
         r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}", r"Policy & Calls & mid & high & mid & high & mid & high \\", r"\midrule"]
    best = {c: max(f(D[(c[0], c[1], p)]["ship_ok"]) + f(D[(c[0], c[1], p)]["rej_ok"]) for _, p, _ in POL) for c in COLS}
    for name, p, calls in POL:
        cells = []
        for c in COLS:
            r = D[(c[0], c[1], p)]; v = f(r["ship_ok"]) + f(r["rej_ok"])
            s = "%.1f (%.0f\\%%)" % (v, 100 * f(r["auto"]))
            cells.append(("\\textbf{%s}" % s) if abs(v - best[c]) < 1e-9 else s)
        L.append(f"{name} & {calls} & " + " & ".join(cells) + r" \\")
    L.append("Constant reject-all & 0 & " + " & ".join("%.1f (cert.\\ %.0f\\%%)" % (f(AR[c]["ar_ok"]), 100 * f(AR[c]["ar_cert"])) for c in COLS) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    write(out, "tab_absolute.tex", "results/absolute_actions/20261108_sw, always_reject_matched/20261108", L)


def tab_router_claims(out):
    """Claim-level routing: pairs the pairwise judge is least sure of get pointwise scores and absolute-level claims."""
    def load(run):
        G = collections.defaultdict(list)
        for r in rows(f"{RES}/{run}/latest/summary.csv"):
            if A2(r) and r["rule"] == "overall":
                G[(r["dataset"], r["variant"])].append(r)
        return G
    C = load("router_controls"); src = os.path.basename(os.path.realpath(f"{RES}/router_controls/latest"))
    m = lambda rr, k: float(np.nanmean([f(x[k]) for x in rr])) if rr and any(f(x[k]) == f(x[k]) for x in rr) else np.nan
    V = [("pairwise graded (G2)", "Graded only"), ("control: routed, no pointwise", "Same claims, no scores"),
         ("router: logistic", "Uncertain half"), ("router: logistic, random gate", "Random half"), ("router: logistic, all routed", "Every pair")]
    L = [r"\begin{tabular}{lrrrrrrr}", r"\toprule",
         r" & \multicolumn{5}{c}{Certified coverage} & \multicolumn{2}{c}{Uncertain half} \\", r"\cmidrule(lr){2-6}\cmidrule(lr){7-8}",
         r"Benchmark & " + " & ".join(v for _, v in V) + r" & Level prec. & Risk \\", r"\midrule"]
    for ds in ("genaibench", "mllm_judge_sp", "imagerewarddb", "genai_arena/generation", "genai_arena/edition", "mllm_judge", "pickapic_u"):
        if not C.get((ds, "pairwise graded (G2)")):
            continue
        cov = [m(C.get((ds, v), []), "source_coverage") for v, _ in V]
        L.append(f"{NAME[ds]} & " + " & ".join("--" if x != x else "%.2f" % x for x in cov) +
                 f" & {m(C.get((ds, 'router: logistic'), []), 'level_precision'):.2f} & {m(C.get((ds, 'router: logistic'), []), 'pooled_risk_source'):.3f} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    write(out, "tab_router_claims.tex", f"results/router_controls/{src}", L)


