def tab_equalcall(out):
    """E2 matched budget: pairwise + pointwise vs three pointwise prompts at six calls per pair."""
    L = [r"\begin{tabular}{llrrrrrrl}", r"\toprule",
         r" & & \multicolumn{4}{c}{Correct decisions / 100 sources} & \multicolumn{2}{c}{Both $-$ pointwise [95\% CI]} & \\",
         r"\cmidrule(lr){3-6}\cmidrule(lr){7-8}",
         r"Benchmark & Bar & Both (6) & 3 prompts (6) & 3 prompts, per-cand. (6) & 1 prompt (2) & vs 3 prompts & vs per-cand. & Reading \\", r"\midrule"]
    for run, ds in (("20261109_imagenhub", "imagenhub/edit"), ("20261109_mllm", "mllm_judge_sp")):
        S = {(r["tau"], r["policy"]): r for r in rows(f"{RES}/e2_budget/{run}/e2b_summary.csv") if A2(r) and r["cert"] == "all" and r["dataset"] == ds}
        K = {(r["tau"], r["a"], r["b"]): r for r in rows(f"{RES}/e2_budget/{run}/e2b_contrasts.csv") if A2(r) and r["dataset"] == ds}
        for t in ("mid", "high"):
            c1, c2 = K[(t, "both", "pw3")], K[(t, "both", "pw3-ind")]
            ci = lambda c: "%+.1f [%+.1f, %+.1f]" % (f(c["d_correct"]), f(c["lo_correct"]), f(c["hi_correct"]))
            rd = "complementary" if c2["reading"].startswith("pairwise complementary") and c1["reading"].startswith("pairwise complementary") else "pointwise suffices"
            L.append(f"{NAME[ds] if t == 'mid' else ''} & {t} & {f(S[(t, 'both')]['correct']):.1f} & {f(S[(t, 'pw3')]['correct']):.1f} & "
                     f"{f(S[(t, 'pw3-ind')]['correct']):.1f} & {f(S[(t, 'pw')]['correct']):.1f} & {ci(c1)} & {ci(c2)} & {rd} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    write(out, "tab_equalcall.tex", "results/e2_budget/20261109_imagenhub, 20261109_mllm", L)


