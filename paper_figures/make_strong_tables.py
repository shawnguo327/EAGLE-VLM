"""Tables for the strongest results that had none (2026-11-09), written into a stand-alone LaTeX folder.  Every number is
read from a saved result file (paths below); nothing is recomputed except means over judges.  alpha = .2 unless stated.
usage (repo root): python paper_figures/make_strong_tables.py --out <folder>/tables"""
import argparse, collections, csv, os, re
import numpy as np

RES = "/media/shawn/C/papers/VLM/results"
NAME = {"genai_arena/edition": "GenAI-Arena edit", "imagenhub/edit": "ImagenHub edit", "visionarena": "VisionArena",
        "mllm_judge": "MLLM-J (pairs)", "mllm_judge_sp": "MLLM-J (scores)", "genaibench": "GenAI-Bench",
        "genai_arena/generation": "GenAI-Arena gen.", "evalmuse": "EvalMuse", "imagenhub/t2i": "ImagenHub t2i",
        "imagerewarddb": "ImageRewardDB", "pickapic_u": "Pick-a-Pic"}
VISUAL = ["genai_arena/edition", "imagenhub/edit", "visionarena", "mllm_judge", "mllm_judge_sp", "genaibench",
          "genai_arena/generation", "evalmuse", "imagenhub/t2i", "imagerewarddb", "pickapic_u"]
JN = {"qwen3vl8b": "Qwen3-VL-8B", "internvl35_8b": "InternVL3.5-8B", "qwen35_9b": "Qwen3.5-9B", "qwen3vl32b": "Qwen3-VL-32B",
      "qwen25vl7b": "Qwen2.5-VL-7B", "internvl35_38b": "InternVL3.5-38B"}
HEAD = "% generated by paper_figures/make_strong_tables.py from {src}; do not edit by hand\n"
f = lambda x: float(x) if x not in (None, "", "nan") else np.nan
red = lambda s: "\\textcolor{red}{%s}" % s
A2 = lambda r: abs(f(r["alpha"]) - .2) < 1e-9


def rows(p):
    return list(csv.DictReader(open(p)))


def write(out, name, src, L):
    open(os.path.join(out, name), "w").write(HEAD.format(src=src) + "\n" + "\n".join(L) + "\n")
    print("wrote", name)


def tab_inputfree(out):
    """E1: the judge's weak claims vs input-free rules that make the same claim, at three risk levels."""
    S = {(r["dataset"], r["method"], r["alpha"]): r for r in rows(f"{RES}/e1_constant/20261109/e1_summary.csv")}
    G = {(r["dataset"], r["alpha"]): r for r in rows(f"{RES}/e1_constant/20261109/e1_gap.csv") if r["reference"] == "WO"}
    L = [r"\begin{tabular}{lrrrrrrr}", r"\toprule",
         r" & & \multicolumn{2}{c}{$\alpha=.1$} & \multicolumn{2}{c}{$\alpha=.2$} & \multicolumn{2}{c}{$\alpha=.3$} \\",
         r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}",
         r"Benchmark & Ties & Judge & Input-free & Judge & Input-free & Judge & Input-free \\", r"\midrule"]
    for ds in VISUAL:
        cells = []
        for al in ("0.1", "0.2", "0.3"):
            wo = f(S[(ds, "WO", al)]["coverage"]); fit = f(S[(ds, "CFIT", al)]["certified_splits"]); env = f(G[(ds, al)]["best_control_certified"])
            cells += [("\\textbf{%.2f}" % wo) if (env == 0 and wo >= .005) else "%.2f" % wo, "%.2f (%.2f)" % (fit, env)]
        L.append(f"{NAME[ds]} & {f(S[(ds, 'WO', '0.2')]['human_tie']):.2f} & " + " & ".join(cells) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    write(out, "tab_inputfree.tex", "results/e1_constant/20261109 (e1_summary.csv, e1_gap.csv)", L)


def tab_visual(out):
    """Image interventions: editing source image removed / swapped (4 judges), MLLM-as-a-Judge question image removed."""
    R = rows(f"{RES}/edit_source_ablation/20261108_j4/edit_source_ablation.csv")
    D = {(r["dataset"], r["judge"], r["cond"]): r for r in R}
    L = [r"\begin{tabular}{llrrrrrrrrrr}", r"\toprule",
         r" & & \multicolumn{3}{c}{Forced-choice accuracy} & \multicolumn{3}{c}{Tie AUROC} & \multicolumn{2}{c}{Recalibrated coverage [risk]} & \multicolumn{2}{c}{Fixed policy: risk} \\",
         r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}\cmidrule(lr){9-10}\cmidrule(lr){11-12}",
         r"Benchmark & Judge & image & none & wrong & image & none & wrong & none & wrong & none & wrong \\", r"\midrule"]
    for ds in ("imagenhub/edit", "genai_arena/edition"):
        js = [j for j in ("qwen3vl8b", "internvl35_8b", "qwen35_9b", "qwen3vl32b") if (ds, j, "src") in D]
