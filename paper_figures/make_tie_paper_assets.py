def f(x):
    try:
        v = float(x); return v if v == v else np.nan
    except (TypeError, ValueError):
        return np.nan


def jm(R, ds, m, col, al=.2):
    v = [f(r[col]) for r in R if r["dataset"] == ds and r["method"] == m and abs(f(r["alpha"]) - al) < 1e-9]
    v = [x for x in v if x == x]
    return (np.mean(v), len(v)) if v else (np.nan, 0)


def cell(v, fmt="{:.2f}"):
    return "--" if v != v else fmt.format(v)


SPARSE = 10        # a risk estimated from answers in fewer than SPARSE of the 100 splits is marked ^s (round 15 review)


def covfmt(c):
    """coverage cell: '--' undefined (not run), 0.00 only for an exact zero, '<.01' for 0 < c < .005 (not rounded to zero)"""
    if c != c:
        return "--"
    if c == 0:
        return "0.00"
    return r"$<$.01" if c < 0.005 else f"{c:.2f}"


def riskfmt(r, al, sa, acc=False):
    """risk (or accuracy 1 - risk) whenever some split answered; red above alpha; ^s when few splits answered"""
    if r != r:
        return "--"
    s_ = f"{(1 - r) if acc else r:.2f}"
    s_ = f"\\textcolor{{red}}{{{s_}}}" if r > al + 1e-9 else s_
    return s_ + ("$^{s}$" if sa == sa and sa < SPARSE else "")


