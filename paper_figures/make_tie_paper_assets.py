def tab_headline(out, al=.2):
    src = {"main": ["certify_source", "certify_baselines", "certify_baselines_pw"],
           "new": ["newdata_certify_source", "newdata_certify_baselines"],
           "bon_mmmu": ["downstream_bon_mmmu", "downstream_bon_mmmu_baselines"], "bon": ["downstream_bon", "downstream_bon_baselines"]}
    cache = {}

    def load(name):
        if name not in cache:
            cache[name] = rows(latest(name) + "/summary.csv")
        return cache[name]
    TR = toe_rows()

    def stat(R, ds, m):
        c, n = jm(R, ds, m, "source_coverage", al); r = jm(R, ds, m, "pooled_risk_source", al)[0]
        sa = np.mean([f(x["splits_answered"]) for x in R if x["dataset"] == ds and x["method"] == m and abs(f(x["alpha"]) - al) < 1e-9
                      and f(x["pooled_risk_source"]) == f(x["pooled_risk_source"])] or [np.nan])
        return c, r, n, sa

    def fs(ds, m):                                              # mean over the judges that have this ToE method's outputs
        R = [r for r in TR if r["dataset"] == ds and r["method"] == m and abs(f(r["alpha"]) - al) < 1e-9]
        if not R:
            return None
        rk = [f(r["pooled_risk_source"]) for r in R]; rk = [x for x in rk if x == x]
        sa = np.mean([f(r["splits_answered"]) for r in R if f(r["pooled_risk_source"]) == f(r["pooled_risk_source"])] or [np.nan])
        return np.mean([f(r["source_coverage"]) for r in R]), (np.mean(rk) if rk else np.nan), sa
    def keeps(c, r):                                              # answers something and keeps the promise
        return c == c and c >= 0.005 and (r != r or r <= al + 1e-9)

    def pc(c, r, bold, sa=np.nan):                                # 'cov & acc'; red accuracy = promise broken; ^s sparse
        cc = covfmt(c)
        if bold and cc != "--":
            cc = f"\\textbf{{{cc}}}"
        return f"{cc} & " + riskfmt(r, al, sa, acc=True)
    L = [HEAD.format(src="certify_source, newdata_certify_source, certify_baselines*, " + ", ".join(TOE_RUNS) + ", downstream_bon*"),
         r"\begin{tabular}{l" + "rr" * 7 + "}", r"\toprule",
         r" & \multicolumn{2}{c}{SCOPE / LEC rule} & \multicolumn{4}{c}{Trust-or-Escalate} & \multicolumn{2}{c}{No weak claim} & "
         r"\multicolumn{2}{c}{Ordinal sets + LTT} & \multicolumn{2}{c}{\textbf{Graded (ours)}} & \multicolumn{2}{c}{Strict-safe (ours)} \\",
         r" & \multicolumn{2}{c}{ties dropped} & \multicolumn{2}{c}{ties dropped} & \multicolumn{2}{c}{ties kept} & "
         r"\multicolumn{2}{c}{best} & \multicolumn{2}{c}{(same claims)} & & & \multicolumn{2}{c}{} \\",
         r"\cmidrule(lr){2-3}\cmidrule(lr){4-7}\cmidrule(lr){8-9}\cmidrule(lr){10-11}\cmidrule(lr){12-13}\cmidrule(lr){14-15}",
         r"Benchmark" + " & Cov. & Acc." * 7 + r" \\", r"\midrule"]
    for ds, nm, kind in HEAD_ROWS:
        if not keep_ds(ds):
            continue
        Rc = load(src[kind][0])
        p1 = stat(Rc, ds, "P1"); g2 = stat(Rc, ds, "G2"); g5 = stat(Rc, ds, "G5")
        if g2[2] == 0:
            continue
        t4, t5 = fs(ds, "T4"), fs(ds, "T5")                       # published few-shot simulated annotators (text responses)
        if t4 is None:                                            # zero-shot persona adaptation where few-shot was not run
            t4, t5 = fs(ds, "T1"), fs(ds, "T2"); mark = "$^{\\ddagger}$"
        else:
            mark = "$^{\\dagger}$"
        cand = []                                                 # outputs without a weak claim that keep the promise
        for m in TIEAWARE:
            for name in src[kind]:
                c, r, n, sa = stat(load(name), ds, m)
                if n and (r != r or r <= al + 1e-9):
                    cand.append((c, r, sa))
        best = (max(cand, key=lambda x: (x[0], -(x[1] if x[1] == x[1] else 1.0)))   # exactly equal coverage: the more
                if cand else (np.nan, np.nan, np.nan))                              # accurate baseline (round-19 review)
        ords = [stat(Rc, ds, m) for m in ("SAo", "SLo")]
        ords = [x for x in ords if x[2]]
        ordc = max(ords, key=lambda x: x[0]) if ords else (np.nan, np.nan, 0, np.nan)
        # bold: the highest (rounded) coverage among the columns that keep the promise
        keep = {"t5": t5, "best": best, "ord": ordc[:2], "g2": g2[:2], "g5": g5[:2]}
        vals = {k: round(v[0], 2) for k, v in keep.items() if v is not None and keeps(v[0], v[1])}
        top = max(vals.values()) if vals else None
        b = {k: (top is not None and k in vals and vals[k] == top) for k in keep}
        toe = ("-- & --" if t4 is None else pc(t4[0], t4[1], False, t4[2]).replace(" & ", mark + " & ", 1)) + " & " + \
              ("-- & --" if t5 is None else pc(t5[0], t5[1], b["t5"], t5[2]))
        L.append(f"{nm} ({g2[2]}) & {pc(p1[0], p1[1], False, p1[3])} & {toe} & {pc(best[0], best[1], b['best'], best[2])} & "
                 f"{pc(ordc[0], ordc[1], b['ord'], ordc[3])} & {pc(g2[0], g2[1], b['g2'], g2[3])} & {pc(g5[0], g5[1], b['g5'], g5[3])} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    open(f"{out}/tables/tab_headline{SUF}.tex", "w").write("\n".join(L) + "\n")


def tab_claim_use(out, al=.2):
    """DRAFT candidate for the main table (review 22 E1; not \\input in the paper until the authors decide): what each
    use can take from the judge, on the same splits and protocol.  Selection: an error iff humans prefer the other candidate;
    preference label: an error iff humans do not prefer the labelled winner (a tie is an error); tie flag: an error iff humans
    prefer one.  FC: the uncertified forced choice; SEL: forced choice certified on the selection loss; PREF: strict claims
    certified on the preference loss; G2 / G5: ours.  Informativeness: mean excluded labels (3 - claim-set size)."""
    C = {(r["dataset"], r["method"], r["use"]): r for r in csv.DictReader(open(latest("claim_use") + "/claim_use_summary.csv"))
         if abs(f(r["alpha"]) - al) < 1e-9}
    W = {(r["dataset"], r["method"]): r for r in csv.DictReader(open(latest("weak_cap") + "/weak_cap_summary.csv"))
         if abs(f(r["alpha"]) - al) < 1e-9}
    def ca(ds, m, use, show_cov=True):
        r = C.get((ds, m, use))
        if r is None:
            return "--"
        c, rk = f(r["coverage"]), f(r["risk"])
        if c != c or c == 0:
            return "0.00" if show_cov else "--"
        acc = 1 - rk; s_ = f"{acc:.2f}" if rk == rk else "--"
        s_ = f"\\textcolor{{red}}{{{s_}}}" if rk == rk and rk > al + 1e-9 else s_
        return f"{covfmt(c)} ({s_})" if show_cov else s_
    ex = lambda r: 2 * (f(r["strict"]) + f(r["tie"])) + f(r["weak"])
    L = [HEAD.format(src="claim_use, weak_cap"), r"\begin{tabular}{lrrrrrrrrr}", r"\toprule",
         r" & \multicolumn{3}{c}{Selection (pick one)} & \multicolumn{3}{c}{Preference label ($k \succ o$)} & Tie flag & \multicolumn{2}{c}{Excluded labels} \\",
         r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-8}\cmidrule(lr){9-10}",
         r"Benchmark (human ties) & FC acc. & SEL & Graded & FC acc. & SCOPE & Certified & Graded & Graded & Weak only \\", r"\midrule"]
    for ds, nm, kind in HEAD_ROWS:
        if not keep_ds(ds):
            continue
        if not any(k[0] == ds for k in C):
            continue
        tie = f(next(r["human_tie"] for k, r in C.items() if k[0] == ds))
        pref_cert = max([(f(C[(ds, m, "preference")]["coverage"]), m) for m in ("PREF", "G5") if (ds, m, "preference") in C], default=(np.nan, ""))
        pc_ = "--" if pref_cert[0] != pref_cert[0] else ca(ds, pref_cert[1], "preference")
        g2w = W.get((ds, "G2")); wo = W.get((ds, "WO"))
        L.append(f"{nm} ({tie:.2f}) & {ca(ds, 'FC', 'selection', False)} & {ca(ds, 'SEL', 'selection')} & {ca(ds, 'G2', 'selection')} & "
                 f"{ca(ds, 'FC', 'preference', False)} & {ca(ds, 'SCOPE', 'preference')} & {pc_} & {ca(ds, 'G2', 'tie')} & "
                 f"{'--' if g2w is None else f'{ex(g2w):.2f}'} & {'--' if wo is None else f'{ex(wo):.2f}'} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    open(f"{out}/tables/tab_claim_use{SUF}.tex", "w").write("\n".join(L) + "\n")


