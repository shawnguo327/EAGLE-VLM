def triage():
    R = rows(f"{RES}/typed_triage/20261107/typed_triage_splits.csv"); G = collections.defaultdict(list)
    for r in R:
        G[(r["dataset"], r["loss"], float(r["alpha"]), r["method"], r["judge"])].append(r)
    S = collections.defaultdict(list)
    for (ds, loss, al, m, j), rr in G.items():
        acc = sum(f(r["acc_mass"]) for r in rr); err = sum(f(r["err_mass"]) for r in rr)
        S[(ds, loss, al, m)].append((np.mean([f(r["automated"]) for r in rr]), err / acc if acc else np.nan,
                                     np.mean([f(r["reject_share"]) for r in rr])))
    return {k: (np.mean([x[0] for x in v]), np.nanmean([x[1] for x in v]) if any(x[1] == x[1] for x in v) else np.nan,
                np.mean([x[2] for x in v]), len(v)) for k, v in S.items()}


