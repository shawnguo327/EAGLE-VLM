"""Main results table (markdown + LaTeX): published tie-dropping certification vs tie-kept baselines vs ours (graded claims,
and graded claims + pointwise absolute-level router), alpha = .2, mean over VLM judges (and Qwen3-VL-32B separately).
Inputs (paper_figures/data/): chain.md, chain_sp.md (pairwise chain), router_v2.jsonl (router).
Router variant shown: 'router: cells' (pre-specified primary: interpretable map); the learned variants are in the appendix table.
usage: python3 paper_figures/make_main_table.py [data_dir]"""
import collections, datetime, json, os, re

import sys
HERE = os.path.dirname(os.path.abspath(__file__)); DATA = sys.argv[1] if len(sys.argv) > 1 else f"{HERE}/data"
STAMP = datetime.datetime.now().strftime("%Y%m%d_%H%M"); OUT = f"{HERE}/tables_{STAMP}"; os.makedirs(OUT, exist_ok=True)
VLM = {"qwen3vl8b", "internvl35_8b", "qwen35_9b", "qwen25vl7b", "qwen3vl32b", "internvl35_38b"}
NICE = {"mllm_judge_sp": "MLLM-J score pairs", "genaibench": "GenAI-Bench", "polaris": "Polaris", "agiqa3k": "AGIQA-3K", "imagerewarddb": "ImageRewardDB", "genai_arena/generation": "GenAI generation",
        "genai_arena/edition": "GenAI edit", "mllm_judge": "MLLM-J pairs", "mtbench_human": "MT-Bench", "arena55k": "Arena-55k"}
SETS = list(NICE); PRIMARY = "router: cells"; ALPHA = 0.2


def mean(v):
    v = [x for x in v if x == x]; return sum(v) / len(v) if v else float("nan")


f2 = lambda v: "--" if v != v else f"{v:.2f}"
# ---- chain (pairwise methods)
ch = collections.defaultdict(list)
for name in ("chain", "chain_sp"):
    p = f"{DATA}/{name}.md"
    if not os.path.exists(p):
        continue
    for line in open(p):
        if not line.startswith("| ") or line.startswith("| set"):
            continue
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if len(c) < 7 or c[1] not in VLM:
            continue
        step = c[4].split()[0]; cell = c[6].split("(")[0]          # alpha 0.2 column
        v = re.findall(r"-?\d+\.\d+|(?<=/ )-(?= /|\s|$)", cell)
        v = [float(x) if x != "-" else float("nan") for x in v]
        if len(v) >= 6:
            ch[(c[0], step)].append(dict(judge=c[1], accept=v[0], size=v[1], decisive=v[2], risk=v[4], viol=v[5]))
# ---- router
rt = [json.loads(l) for l in open(f"{DATA}/router_v2.jsonl")] if os.path.exists(f"{DATA}/router_v2.jsonl") else []
R = collections.defaultdict(list)
for d in rt:
    if d["alpha"] == ALPHA and d["judge"] in VLM:
        R[(d["set"], d["variant"], d["rule"])].append(d)


def agg(rows, k, judge=None):
    return mean([r[k] for r in rows if judge is None or r["judge"] == judge])


def block(judge=None):
    out = []
    for s in SETS:
        p1 = ch.get((s, "P1"), []); base = [ch.get((s, st), []) for st in ("P2", "P4")]
        g2 = ch.get((s, "G2"), []); rr = R.get((s, PRIMARY, "overall"), []); rj = R.get((s, PRIMARY, "every level"), [])
        bacc = max([agg(b, "accept", judge) for b in base if b] or [float("nan")])
        out.append(dict(set=s, p1_risk=agg(p1, "risk", judge), p1_viol=agg(p1, "viol", judge), base_acc=bacc,
                        g2_acc=agg(g2, "accept", judge), g2_risk=agg(g2, "risk", judge), g2_viol=agg(g2, "viol", judge),
                        r_acc=agg(rr, "accept", judge), r_inf=agg(rr, "informative", judge), r_lvl=agg(rr, "level", judge),
                        r_prec=agg(rr, "level_prec", judge), r_risk=agg(rr, "risk", judge), r_viol=agg(rr, "violation", judge),
                        rj_acc=agg(rj, "accept", judge), rj_inf=agg(rj, "informative", judge),
                        c_acc=agg(R.get((s, "control: routed, no pointwise", "overall"), []), "accept", judge),
                        c_inf=agg(R.get((s, "control: routed, no pointwise", "overall"), []), "informative", judge)))
    return out


md = [f"# Main table (alpha = {ALPHA}), generated {STAMP}", "",
      "| set | judges | SCOPE published: risk / viol | best tie-kept baseline: accept | ours graded: accept / risk / viol | "
      "control (routed, no pointwise): accept / informative | ours + router: accept / informative / level (prec) / risk / viol | ours + router, every level: accept / informative |",
      "|---|---|---|---|---|---|---|---|"]
tex = ["% auto-generated by make_main_table.py " + STAMP, "\\begin{table*}[t]\\centering\\small", "\\setlength{\\tabcolsep}{3pt}",
       "\\caption{Main results with human ties kept at test time ($\\alpha=0.2$, $\\delta=0.1$, 100 random 25/25/50 splits; mean over VLM judges, "
       "Qwen3-VL-32B in brackets where it differs). Published tie-dropping certification (SCOPE) violates the risk bound in almost every split; "
       "the same methods calibrated with ties abstain on nearly all pairs (best of SCOPE-with-ties and strict claims with all our signals). "
       "Graded claims keep the risk below $\\alpha$; routing pairwise-uncertain pairs to pointwise absolute-level claims (`no clear winner', "
       "`both unacceptable') certifies more pairs. Control = the same routing and level claims without pointwise scores (estimated error = base rate); gains above the control are due to pointwise routing. On ImageRewardDB the control matches the router: `no clear winner' is true for most pairs (human ratings within one point), so that gain is not attributable to pointwise. Informative = strict + absolute-level claims; level precision = share of correct level claims.}",
       "\\label{tab:main}", "\\begin{tabular}{l cc c ccc c ccccc}", "\\toprule",
       " & \\multicolumn{2}{c}{SCOPE (published)} & Tie-kept & \\multicolumn{3}{c}{Ours: graded} & Control & \\multicolumn{5}{c}{Ours: graded + pointwise router} \\\\",
       "\\cmidrule(lr){2-3}\\cmidrule(lr){4-4}\\cmidrule(lr){5-7}\\cmidrule(lr){8-8}\\cmidrule(lr){9-13}",
       "Dataset & risk & viol. & accept & accept & risk & viol. & accept & accept & inform. & level (prec.) & risk & viol. \\\\", "\\midrule"]
B = block(); B32 = {r["set"]: r for r in block("qwen3vl32b")}
for r in B:
    b = B32.get(r["set"], {})
    md.append(f"| {NICE[r['set']]} | mean | {f2(r['p1_risk'])} / {f2(r['p1_viol'])} | {f2(r['base_acc'])} | {f2(r['g2_acc'])} / {f2(r['g2_risk'])} / {f2(r['g2_viol'])} | "
              f"{f2(r['c_acc'])} / {f2(r['c_inf'])} | {f2(r['r_acc'])} / {f2(r['r_inf'])} / {f2(r['r_lvl'])} ({f2(r['r_prec'])}) / {f2(r['r_risk'])} / {f2(r['r_viol'])} | {f2(r['rj_acc'])} / {f2(r['rj_inf'])} |")
    md.append(f"| | 32B | {f2(b.get('p1_risk', float('nan')))} / {f2(b.get('p1_viol', float('nan')))} | {f2(b.get('base_acc', float('nan')))} | "
              f"{f2(b.get('g2_acc', float('nan')))} / {f2(b.get('g2_risk', float('nan')))} / {f2(b.get('g2_viol', float('nan')))} | "
              f"{f2(b.get('c_acc', float('nan')))} / {f2(b.get('c_inf', float('nan')))} | {f2(b.get('r_acc', float('nan')))} / {f2(b.get('r_inf', float('nan')))} / {f2(b.get('r_lvl', float('nan')))} ({f2(b.get('r_prec', float('nan')))}) / "
              f"{f2(b.get('r_risk', float('nan')))} / {f2(b.get('r_viol', float('nan')))} | {f2(b.get('rj_acc', float('nan')))} / {f2(b.get('rj_inf', float('nan')))} |")
    br = lambda k: "" if not b or abs(b.get(k, float("nan")) - r[k]) < .03 or b.get(k) != b.get(k) else f" ({b[k]:.2f})"
    router = (f"\\textbf{{{f2(r['r_acc'])}}}{br('r_acc')} & {f2(r['r_inf'])}{br('r_inf')} & {f2(r['r_lvl'])} ({f2(r['r_prec'])}) & {f2(r['r_risk'])} & {f2(r['r_viol'])}"
              if r["r_acc"] == r["r_acc"] else "\\multicolumn{5}{c}{\\textit{no absolute human reference}}")
    ctrl = f"{f2(r['c_acc'])}" if r["c_acc"] == r["c_acc"] else "--"
    tex.append(f"{NICE[r['set']]} & {f2(r['p1_risk'])} & {f2(r['p1_viol'])} & {f2(r['base_acc'])}{br('base_acc')} & "
               f"{f2(r['g2_acc'])}{br('g2_acc')} & {f2(r['g2_risk'])} & {f2(r['g2_viol'])} & {ctrl} & {router} \\\\")
tex += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
# appendix: router variants
md += ["", "## Router variants (alpha .2, mean over judges): accept / informative / level (prec) / risk", "",
       "| set | rule | " + " | ".join(["pairwise graded (G2)", "control: routed, no pointwise", "router: cells", "router: logistic", "router: jury pointwise"]) + " |", "|---|---|---|---|---|---|---|"]
for s in SETS:
    for rule in ("overall", "every level"):
        cells = []
        for v in ("pairwise graded (G2)", "control: routed, no pointwise", "router: cells", "router: logistic", "router: jury pointwise"):
            rr = R.get((s, v, rule), [])
            cells.append("--" if not rr else f"{f2(agg(rr, 'accept'))} / {f2(agg(rr, 'informative'))} / {f2(agg(rr, 'level'))} ({f2(agg(rr, 'level_prec'))}) / {f2(agg(rr, 'risk'))}")
        if any(c != "--" for c in cells):
            md.append(f"| {NICE[s]} | {rule} | " + " | ".join(cells) + " |")
open(f"{OUT}/main_table.md", "w").write("\n".join(md) + "\n"); open(f"{OUT}/tab_main.tex", "w").write("\n".join(tex) + "\n")
print(OUT); print("\n".join(md))
