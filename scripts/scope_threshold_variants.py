"""SCOPE threshold variants on the real benchmarks (review round 6, R6-N1/N2): the earlier float boundary (P1f/P2f), the
exact observed-score rule now used for all SCOPE rows (P1/P2) and the published supremum read literally (P1u/P2u), on the
same fixed splits.  Per benchmark (mean over the general VLM judges, alpha .2): the share of judge-split runs whose accepted
set differs from the exact rule's (thresholds are nested, so a different accepted count means a different set), and
source-uniform coverage and pooled source risk under each reading.  Writes tab_scope_variants.tex.
    python scripts/scope_threshold_variants.py --run .../results/certify_source/latest --out <overleaf>/tables_auto
"""
import argparse, collections, csv, gzip, math, os

J6 = ["qwen3vl8b", "internvl35_8b", "qwen35_9b", "qwen25vl7b", "qwen3vl32b", "internvl35_38b"]
DS = [("mllm_judge", "MLLM-J (pairs)"), ("mllm_judge_sp", "MLLM-J (scores)"), ("genaibench", "GenAI-Bench"),
      ("genai_arena/generation", "GenAI-Arena gen."), ("genai_arena/edition", "GenAI-Arena edit"), ("pickapic_u", "Pick-a-Pic"),
      ("imagerewarddb", "ImageRewardDB"), ("mtbench_human", "MT-Bench (text)"), ("arena55k", "Chatbot Arena (text)")]


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--run", required=True); ap.add_argument("--out", required=True)
    ap.add_argument("--alpha", type=float, default=0.2); a = ap.parse_args()
    run = os.path.realpath(a.run)
    S = collections.defaultdict(list)
    for r in csv.DictReader(open(os.path.join(run, "summary.csv"))):
        if r["judge"] in J6 and abs(float(r["alpha"]) - a.alpha) < 1e-9:
            S[(r["dataset"], r["method"])].append(r)
    acc = collections.defaultdict(dict)                    # (dataset, judge, split) -> method -> accepted
    with gzip.open(os.path.join(run, "splits.csv.gz"), "rt") as fh:
        for r in csv.DictReader(fh):
            if r["judge"] in J6 and abs(float(r["alpha"]) - a.alpha) < 1e-9 and r["method"] in ("P1", "P1f", "P1u", "P2", "P2f", "P2u"):
                acc[(r["dataset"], r["judge"], r["split"])][r["method"]] = int(float(r["accepted"]))

    def mean(rs, c):
        v = [float(r[c]) for r in rs if r.get(c) not in ("", None) and not math.isnan(float(r[c]))]
        return sum(v) / len(v) if v else float("nan")
    f = lambda x, d=2: "--" if x != x else f"{x:.{d}f}"
    L = [f"% generated by scripts/scope_threshold_variants.py from {os.path.basename(os.path.dirname(run))}/{os.path.basename(run)}, "
         f"alpha {a.alpha}; do not edit by hand", "",
         "\\begin{tabular}{llrrrrrrrr}", "\\toprule",
         " & & \\multicolumn{2}{c}{Changed set} & \\multicolumn{3}{c}{Coverage} & \\multicolumn{3}{c}{Pooled risk} \\\\",
         "\\cmidrule(lr){3-4}\\cmidrule(lr){5-7}\\cmidrule(lr){8-10}",
         "Benchmark & Rule & float & sup & float & exact & sup & float & exact & sup \\\\", "\\midrule"]
    for ds, name in DS:
        for k, base in enumerate(("P1", "P2")):
            keys = [kk for kk in acc if kk[0] == ds and all(m in acc[kk] for m in (base, base + "f", base + "u"))]
            if not keys:
                continue
            chf = sum(acc[kk][base + "f"] != acc[kk][base] for kk in keys) / len(keys)
            chu = sum(acc[kk][base + "u"] != acc[kk][base] for kk in keys) / len(keys)
            cov = [mean(S[(ds, base + s)], "source_coverage") for s in ("f", "", "u")]
            rsk = [mean(S[(ds, base + s)], "pooled_risk_source") for s in ("f", "", "u")]
            lab = "SCOPE" if base == "P1" else "SCOPE + ties"
            L.append(f"{name if k == 0 else ''} & {lab} & {100 * chf:.0f}\\% & {100 * chu:.0f}\\% & "
                     + " & ".join(f(x) for x in cov) + " & " + " & ".join(f(x, 3) for x in rsk) + " \\\\")
        L.append("\\midrule")
    L[-1] = "\\bottomrule"; L.append("\\end{tabular}")
    open(os.path.join(a.out, "tab_scope_variants.tex"), "w").write("\n".join(L) + "\n"); print("wrote tab_scope_variants.tex from", run)


if __name__ == "__main__":
    main()
