"""Supplement ablation table (source level, alpha .2, mean over the general VLM judges): certified coverage of graded
claims without the calibrator (G0), with forced-choice features only (G2b), without weak claims (G2s), with every claim
level held below alpha (G3), with overall and strict risk held below alpha by one threshold (G4) or by separate thresholds
(G5, strict-safe), next to the graded rule (G2); last column: the largest mean source risk of the row.  Standard library.
    python scripts/ablation_table.py --run /media/shawn/C/papers/VLM/results/certify_source/latest --out <overleaf>/tables_auto
"""
import argparse, collections, csv, math, os

J6 = ["qwen3vl8b", "internvl35_8b", "qwen35_9b", "qwen25vl7b", "qwen3vl32b", "internvl35_38b"]
DS = [("mllm_judge", "MLLM-J\\\\pairs"), ("mllm_judge_sp", "MLLM-J\\\\scores"), ("genaibench", "GenAI-\\\\Bench"),
      ("genai_arena/generation", "Arena\\\\gen."), ("genai_arena/edition", "Arena\\\\edit"), ("pickapic_u", "Pick-\\\\a-Pic"),
      ("imagerewarddb", "Image-\\\\Reward"), ("mtbench_human", "MT-\\\\Bench"), ("arena55k", "Chatbot\\\\Arena")]
ROWS = [("G2", "Graded (ours)"), ("G0", "no calibrator"), ("G2b", "forced-choice features only"), ("G2s", "no weak claims"),
        ("G3", "every level $\\le\\alpha$"), ("G4", "overall and strict, one $\\lambda$"), ("G5", "strict-safe")]


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--run", required=True); ap.add_argument("--out", required=True)
    ap.add_argument("--alpha", type=float, default=0.2); a = ap.parse_args()
    run = os.path.realpath(a.run); S = collections.defaultdict(list)
    for r in csv.DictReader(open(os.path.join(run, "summary.csv"))):
        if r["judge"] in J6 and abs(float(r["alpha"]) - a.alpha) < 1e-9:
            S[(r["dataset"], r["method"])].append(r)

    def mean(rs, c):
        v = [float(r[c]) for r in rs if r.get(c) not in ("", None) and not math.isnan(float(r[c]))]
        return sum(v) / len(v) if v else float("nan")
    L = [f"% generated by scripts/ablation_table.py from {os.path.basename(os.path.dirname(run))}/{os.path.basename(run)}, "
         f"alpha {a.alpha}; do not edit by hand", "",
         "\\begin{tabular}{l" + "r" * len(DS) + "r}", "\\toprule",
         "Variant & " + " & ".join(f"\\shortstack{{{n}}}" for _, n in DS) + " & \\shortstack{max\\\\pooled} \\\\", "\\midrule"]
    for code, name in ROWS:
        covs = [mean(S.get((d, code), []), "source_coverage") for d, _ in DS]
        risks = [mean(S.get((d, code), []), "pooled_risk_source") for d, _ in DS]
        risks = [x for x in risks if x == x]
        L.append(f"{name} & " + " & ".join("--" if x != x else f"{x:.2f}" for x in covs)
                 + f" & {max(risks):.3f} \\\\" if risks else " & -- \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    open(os.path.join(a.out, "tab_ablations.tex"), "w").write("\n".join(L) + "\n"); print("wrote tab_ablations.tex from", run)


if __name__ == "__main__":
    main()
