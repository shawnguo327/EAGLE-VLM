"""LaTeX tables for the improvement-plan ablations (results/<name>/latest/summary.csv of eaglevlm.pipeline.ablate):
tab_factorial.tex (signal x claim family), tab_tiechannel.tex (instance p(T) vs tie prior), tab_selection.tex
(two-candidate selection with escalation).  Means over the general VLM judges at one alpha; standard library only.

    python scripts/ablate_tables.py --results /media/shawn/C/papers/VLM/results --name ablate_source --out <overleaf>/tables_auto
"""
import argparse, collections, csv, math, os

J6 = ["qwen3vl8b", "internvl35_8b", "qwen35_9b", "qwen25vl7b", "qwen3vl32b", "internvl35_38b"]
DS = [("mllm_judge", "MLLM-J (pairs)"), ("mllm_judge_sp", "MLLM-J (scores)"), ("genaibench", "GenAI-Bench"),
      ("genai_arena/generation", "GenAI-Arena gen."), ("genai_arena/edition", "GenAI-Arena edit"), ("pickapic_u", "Pick-a-Pic"),
      ("imagerewarddb", "ImageRewardDB"), ("mtbench_human", "MT-Bench"), ("arena55k", "Chatbot Arena")]


def load(path, alpha):
    acc = collections.defaultdict(list)
    for r in csv.DictReader(open(path)):
        if r["judge"] in J6 and abs(float(r["alpha"]) - alpha) < 1e-9:
            acc[(r["dataset"], r["method"])].append(r)
    return acc


def mean(rows, col):
    v = [float(r[col]) for r in rows if r.get(col) not in ("", None) and not math.isnan(float(r[col]))]
    return sum(v) / len(v) if v else float("nan")


def sig(rows, lo, hi):
    """judges whose split-0 paired source-bootstrap interval is above / below zero"""
    up = sum(1 for r in rows if r[lo] not in ("", "nan") and float(r[lo]) > 0)
    dn = sum(1 for r in rows if r[hi] not in ("", "nan") and float(r[hi]) < 0)
    return up, dn, len(rows)


def f(x, d=2):
    return "--" if x != x else f"{x:.{d}f}"


def contrast(acc, ds, c, col="d_excluded", lo="holdout_excl_lo", hi="holdout_excl_hi"):
    rows = acc.get((ds, "D:" + c), [])
    if not rows:
        return "--"
    up, dn, n = sig(rows, lo, hi); m = mean(rows, col)
    return f"{m:+.2f}" + (f"$^{{{up}/{n}}}$" if up else "")


def write(out, name, head, rows, note):
    with open(os.path.join(out, name), "w") as fh:
        fh.write(f"% generated by scripts/ablate_tables.py from {note}; do not edit by hand\n\n")
        fh.write(head + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--results", required=True); ap.add_argument("--name", default="ablate_source")
    ap.add_argument("--out", required=True); ap.add_argument("--alpha", type=float, default=0.2); a = ap.parse_args()
    run = os.path.realpath(os.path.join(a.results, a.name, "latest")); acc = load(os.path.join(run, "summary.csv"), a.alpha)
    note = f"{a.name}/{os.path.basename(run)}, alpha {a.alpha}"
    ds = [(d, n) for d, n in DS if (d, "F02") in acc]
    head = ("\\begin{tabular}{lrrrrrrrr}\n\\toprule\n & \\multicolumn{3}{c}{Pairwise signals} & \\multicolumn{3}{c}{+ pointwise}"
            " & \\multicolumn{2}{c}{Contrast} \\\\\nBenchmark & $\\{A\\},\\{B\\}$ & $+\\{T\\}$ & $+$weak & $\\{A\\},\\{B\\}$ & $+\\{T\\}$ & $+$weak"
            " & weak & pointw. \\\\\n\\midrule\n")
    rows = [f"{n} & " + " & ".join(f(mean(acc.get((d, m), []), "excluded")) for m in ("F00", "F01", "F02", "F10", "F11", "F12"))
            + f" & {contrast(acc, d, 'F02-F01')} & {contrast(acc, d, 'F12-F02')} \\\\" for d, n in ds]
    write(a.out, "tab_factorial.tex", head, rows, note)
    head = ("\\begin{tabular}{lrrrrrrr}\n\\toprule\n & \\multicolumn{5}{c}{Excluded labels} & \\multicolumn{2}{c}{Tie AUROC} \\\\\n"
            "Benchmark & B0 & B1 & B2 & B3 & B4 & B1 & B3 \\\\\n\\midrule\n")
    rows = [f"{n} & " + " & ".join(f(mean(acc.get((d, m), []), "excluded")) for m in ("B0", "B1", "B2", "B3", "B4"))
            + " & " + " & ".join(f(mean(acc.get((d, m), []), "tie_auroc")) for m in ("B1", "B3")) + " \\\\" for d, n in ds]
    write(a.out, "tab_tiechannel.tex", head, rows, note)
    head = ("\\begin{tabular}{lrrrrrr}\n\\toprule\n & \\multicolumn{5}{c}{Automated share at certified selection risk} & Risk \\\\\n"
            "Benchmark & U1s & U1 & U1c & U2 & U3 & U2 \\\\\n\\midrule\n")
    rows = [f"{n} & " + " & ".join(f(mean(acc.get((d, m), []), "acceptance")) for m in ("U1s", "U1", "U1c", "U2", "U3"))
            + f" & {f(mean(acc.get((d, 'U2'), []), 'risk_source'), 3)} \\\\" for d, n in ds]
    write(a.out, "tab_selection.tex", head, rows, note)
    rc = os.path.realpath(os.path.join(a.results, "router_controls", "latest", "summary.csv"))
    if os.path.exists(rc):                                   # improvement plan experiment 4: router same-target controls
        V = [("pairwise graded (G2)", "Graded"), ("control: routed, no pointwise", "Control"),
             ("R1: routed, pairwise-only level head", "Pairwise-only"), ("router: cells", "Tie map"), ("router: logistic", "Logistic"),
             ("R2: routed, unified augmented head", "Unified"), ("router: logistic, random gate", "Random gate"),
             ("router: logistic, all routed", "All routed"), ("router: jury pointwise", "Jury")]
        R = collections.defaultdict(list)
        for r in csv.DictReader(open(rc)):
            if r["judge"] in J6 and abs(float(r["alpha"]) - a.alpha) < 1e-9:
                R[(r["dataset"], r["variant"], r["rule"])].append(r)
        rds = [(d, n) for d, n in [("mllm_judge_sp", "MLLM-J (scores)"), ("genaibench", "GenAI-Bench"), ("imagerewarddb", "ImageRewardDB"),
                                   ("agiqa3k", "AGIQA-3K")] if (d, V[0][0], "overall") in R]
        head = ("\\begin{tabular}{ll" + "r" * len(V) + "}\n\\toprule\n & & " + " & ".join(lab for _, lab in V) + " \\\\\n\\midrule\n")
        rows = []
        for d, n in rds:
            rows.append(f"{n} & Cov. & " + " & ".join(f(mean(R.get((d, v, 'overall'), []), "acceptance")) for v, _ in V) + " \\\\")
            rows.append(f" & Abs.$^\\dagger$ & " + " & ".join(f(mean(R.get((d, v, 'overall+absolute'), []), "level_correct_share")) for v, _ in V) + " \\\\")
        write(a.out, "tab_router_controls.tex", head, rows, f"router_controls/{os.path.basename(os.path.dirname(rc))}, alpha {a.alpha}")
    print("written to", a.out, "from", note)


if __name__ == "__main__":
    main()
