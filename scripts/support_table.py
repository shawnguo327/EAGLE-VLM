"""Per-judge source support of the graded rule (review round 6, R6-N5): for each benchmark and judge, over the 100
source-level splits at one alpha, the number of splits with any answer, the median number of test sources with at least
one accepted pair (N+) and the median accepted source mass sum_g a_g (the denominator of the source-uniform risk).
Standard library only; writes tab_support.tex.
    python scripts/support_table.py --run /media/shawn/C/papers/VLM/results/certify_source/latest --out <overleaf>/tables_auto
"""
import argparse, collections, csv, gzip, os, statistics

J6 = [("qwen3vl8b", "Qwen3-VL-8B"), ("internvl35_8b", "InternVL3.5-8B"), ("qwen35_9b", "Qwen3.5-9B"),
      ("qwen25vl7b", "Qwen2.5-VL-7B"), ("qwen3vl32b", "Qwen3-VL-32B"), ("internvl35_38b", "InternVL3.5-38B")]
DS = [("mllm_judge", "MLLM-J (pairs)"), ("mllm_judge_sp", "MLLM-J (scores)"), ("genaibench", "GenAI-Bench"),
      ("genai_arena/generation", "GenAI-Arena gen."), ("genai_arena/edition", "GenAI-Arena edit"), ("pickapic_u", "Pick-a-Pic"),
      ("imagerewarddb", "ImageRewardDB"), ("mtbench_human", "MT-Bench (text)"), ("arena55k", "Chatbot Arena (text)")]


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--run", required=True); ap.add_argument("--out", required=True)
    ap.add_argument("--method", default="G2"); ap.add_argument("--alpha", type=float, default=0.2); a = ap.parse_args()
    run = os.path.realpath(a.run); R = collections.defaultdict(list)
    with gzip.open(os.path.join(run, "splits.csv.gz"), "rt") as fh:
        for r in csv.DictReader(fh):
            if r["method"] == a.method and abs(float(r["alpha"]) - a.alpha) < 1e-9:
                R[(r["dataset"], r["judge"])].append(r)
    L = [f"% generated by scripts/support_table.py from {os.path.basename(os.path.dirname(run))}/{os.path.basename(run)}, "
         f"{a.method}, alpha {a.alpha}; do not edit by hand", "",
         "\\begin{tabular}{l" + "c" * len(J6) + "}", "\\toprule", "Benchmark & " + " & ".join(n for _, n in J6) + " \\\\", "\\midrule"]
    for ds, name in DS:
        cells = []
        for j, _ in J6:
            rs = R.get((ds, j))
            if not rs:
                cells.append("--"); continue
            ans = sum(int(float(r["accepted"])) > 0 for r in rs)
            npos = statistics.median(int(float(r["accepted_sources"])) for r in rs)
            mass = statistics.median(float(r["src_acc_mass"]) for r in rs)
            cells.append(f"{ans} / {npos:g} / {mass:.0f}")
        L.append(f"{name} & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    open(os.path.join(a.out, "tab_support.tex"), "w").write("\n".join(L) + "\n"); print("wrote tab_support.tex from", run)


if __name__ == "__main__":
    main()
