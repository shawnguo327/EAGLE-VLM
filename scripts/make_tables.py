"""LaTeX (booktabs) tables for the paper from the markdown result tables in paper_figures/data/.
  tab_certify.tex     published tie-dropping certification vs the same methods with ties kept vs ours (mean over VLM judges)
  tab_decompose.tex   'pairwise-uncertain' is not 'tie': composition of the most uncertain third and type detection
                      (pairwise vs pointwise AUROC), mean over judges
  tab_routing.tex     main setting (MLLM-as-a-Judge score pairs): single judge vs jury vs jury + pointwise routing
  tab_inflation.tex   reported accuracy (ties dropped) vs ties kept, judge tie rate vs human tie rate
Output: paper_figures/tables_<stamp>/ .  usage: python3 paper_figures/make_tables.py"""
import collections, datetime, os, re

HERE = os.path.dirname(os.path.abspath(__file__)); DATA = f"{HERE}/data"
STAMP = datetime.datetime.now().strftime("%Y%m%d_%H%M"); OUT = f"{HERE}/tables_{STAMP}"; os.makedirs(OUT, exist_ok=True)
NICE = {"mllm_judge_sp": "MLLM-J (score pairs)", "mllm_judge": "MLLM-J (pairs)", "mtbench_human": "MT-Bench",
        "arena55k": "Arena-55k", "genai_arena/edition": "GenAI edit", "genai_arena/generation": "GenAI gen.",
        "pickapic_u": "Pick-a-Pic", "imagerewarddb": "ImageRewardDB"}
VLM = {"qwen3vl8b", "internvl35_8b", "qwen35_9b", "qwen25vl7b", "qwen3vl32b"}


def rows(name):
    out = []
    for line in open(f"{DATA}/{name}.md"):
        if line.startswith("| ") and not line.startswith("| set") and not line.startswith("| judge") and "---" not in line:
            out.append([c.strip() for c in line.strip().strip("|").split("|")])
    return out


def nums(s):
    return [float(x) for x in re.findall(r"-?\d+\.\d+", s.split("(")[0])]


def mean(v):
    v = [x for x in v if x == x]; return sum(v) / len(v) if v else float("nan")


f2 = lambda v: "--" if v != v else f"{v:.2f}"

# ---------------- Table: certification chain (alpha .2), mean over VLM judges
chain = rows("chain") + rows("chain_sp")
acc = collections.defaultdict(list)          # (set, step) -> [(size, risk, viol, decisive, strict err)]
for c in chain:
    ds, j, step = c[0], c[1], c[4].split()[0]
    if j not in VLM:
        continue
    cell = c[6]                              # alpha 0.2 (columns: alpha 0.1, 0.2, 0.3)
    v = [float(x) if x != "-" else float("nan") for x in re.findall(r"-?\d+\.\d+|(?<=/ )-(?= /|\s|$)", cell.split("(")[0])]
    if len(v) >= 6:
        acc[(ds, step)].append(v)
SETS = ["mllm_judge_sp", "mllm_judge", "mtbench_human", "arena55k", "genai_arena/edition", "genai_arena/generation"]
STEPS = [("P1", "SCOPE, as published (calibrated w/o ties)"), ("T1", "Trust-or-Escalate, as published$^\\dagger$"),
         ("P2", "SCOPE, ties kept in calibration"), ("P4", "strict claims + all our signals + head"),
         ("G2", "\\textbf{graded claims (ours)}"), ("G3", "\\textbf{graded, every level $\\le\\alpha$ (ours)}")]
L = ["% auto-generated by make_tables.py " + STAMP, "\\begin{table*}[t]\\centering\\small", "\\setlength{\\tabcolsep}{3.5pt}",
     "\\caption{Certified judging when human ties are kept at test time ($\\alpha=0.2$, $\\delta=0.1$, 100 random splits, mean over five VLM judges). "
     "Each cell: mean prediction-set size (1 = one claim, 2 = weak claim, 3 = abstain; lower is more informative) / realised selective risk / "
     "violation rate (share of splits with risk $>\\alpha$). Published protocols violate the guarantee in almost every split; "
     "keeping ties in their calibration restores validity but they abstain on nearly everything, even with all of our signal components (strict + head). "
     "Graded claims keep the risk below $\\alpha$ and remain informative. $^\\dagger$persona runs only on 1{,}500-pair subsets.}",
     "\\label{tab:certify}", "\\begin{tabular}{l" + "c" * len(SETS) + "}", "\\toprule",
     "Method & " + " & ".join(NICE[s] for s in SETS) + " \\\\", "\\midrule"]
for st, name in STEPS:
    cells = []
    for s in SETS:
        V = acc.get((s, st))
        if not V:
            cells.append("--"); continue
        sz, rk, vi = mean([v[1] for v in V]), mean([v[4] for v in V]), mean([v[5] for v in V])
        cells.append(f"{f2(sz)} / {f2(rk)} / {f2(vi)}")
    if all(c == "--" for c in cells):
        continue
    L.append(f"{name} & " + " & ".join(cells) + " \\\\")
    if st == "T1":
        L.append("\\midrule")
L += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
open(f"{OUT}/tab_certify.tex", "w").write("\n".join(L) + "\n")

# ---------------- Table: decomposition of the pairwise-uncertain third
dec = open(f"{DATA}/decompose_v2.md").read().split("\n## ")
comp, auc = collections.defaultdict(list), collections.defaultdict(list)
for block in dec[1:]:
    name = block.split("\n")[0].strip()
    if name.startswith("(d)"):
        continue
    for line in block.split("\n"):
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if len(c) == 3 and c[1].startswith("all:"):
            for k, v in re.findall(r"([a-z-]+) ([0-9.]+)", c[2]):
                comp[(name, k)].append(float(v))
        if len(c) == 5 and re.match(r"[a-z-]+ \(", c[1]) and c[2] != "pairwise":
            k = c[1].split()[0]
            auc[(name, k, "pw")].append(float(c[2])); auc[(name, k, "pt")].append(float(c[3]))
TYPES = [("tie-bad", "both bad"), ("tie-bothbad", "both bad"), ("tie-good", "both good"), ("tie-equal", "equally good"),
         ("decided-subtle", "decided, subtle"), ("decided", "decided")]
L = ["% auto-generated by make_tables.py " + STAMP, "\\begin{table}[t]\\centering\\small", "\\setlength{\\tabcolsep}{3pt}",
     "\\caption{`Pairwise-uncertain' is not `tie'. Within the third of pairs with the highest forced-choice entropy we report the share of each "
     "human-defined pair type and the 5-fold CV AUROC for detecting it from pairwise signals vs pointwise (absolute) scores (mean over judges). "
     "Types come from human references: GenAI-Arena vote types; for MLLM-as-a-Judge score pairs, the human 1--5 score of both answers "
     "(both bad: both $\\le 2$; both good: both $\\ge 4$; subtle: decided by one point). Pointwise scores recover the absolute-level tie types "
     "that the pairwise prompt cannot see, but not subtle decided pairs.}", "\\label{tab:decompose}",
     "\\begin{tabular}{llccc}", "\\toprule", "Dataset & Pair type & Share & AUROC pairwise & AUROC pointwise \\\\", "\\midrule"]
for ds in ("mllm_judge_sp", "genai_arena/generation", "genai_arena/edition"):
    first = True
    for k, lab in TYPES:
        if (ds, k, "pw") not in auc:
            continue
        sh = mean(comp.get((ds, k), [float("nan")]))
        pw, pt = mean(auc[(ds, k, "pw")]), mean(auc[(ds, k, "pt")])
        best = (lambda a, b: (f"\\textbf{{{a:.2f}}}", f"{b:.2f}") if a > b + .02 else (f"{a:.2f}", f"\\textbf{{{b:.2f}}}") if b > a + .02 else (f"{a:.2f}", f"{b:.2f}"))(pw, pt)
        L.append(f"{NICE[ds] if first else ''} & {lab} & {f2(sh)} & {best[0]} & {best[1]} \\\\"); first = False
    L.append("\\midrule")
L[-1] = "\\bottomrule"
L += ["\\end{tabular}", "\\end{table}"]
open(f"{OUT}/tab_decompose.tex", "w").write("\n".join(L) + "\n")

# ---------------- Table: routing in the main setting
rt = rows("route_exp_sp")
L = ["% auto-generated by make_tables.py " + STAMP, "\\begin{table}[t]\\centering\\small", "\\setlength{\\tabcolsep}{3pt}",
     "\\caption{Main setting (MLLM-as-a-Judge score pairs, 9{,}865 pairs, 29\\% ties): routing pairwise judgements together with pointwise "
     "absolute scores. Cells: acceptance / set size / decisive (strict) share / strict-claim error. `Every level' certifies strict, tie and weak claims "
     "simultaneously at $\\alpha$ (intersection--union LTT).}", "\\label{tab:routing}", "\\begin{tabular}{lcc}", "\\toprule",
     "Judge signals & $\\alpha=.2$, overall risk & $\\alpha=.3$, every level $\\le\\alpha$ \\\\", "\\midrule"]
pick = {"base: qwen3vl32b": "Qwen3-VL-32B (pairwise)", "E1 jury (5 judges)": "jury of 5 VLMs (pairwise)",
        "E1+pt jury + pointwise (5)": "\\textbf{jury + pointwise routing}"}
for key, lab in pick.items():
    g = [c for c in rt if c[1] == key and c[2] == "graded"]; jt = [c for c in rt if c[1] == key and c[2] == "joint"]
    if not g or not jt:
        continue
    a2 = nums(g[0][4]); a3 = nums(jt[0][5])
    fmt = lambda v: f"{v[0]:.2f} / {v[1]:.2f} / {v[2]:.2f} / " + (f"{v[4]:.2f}" if len(v) > 4 else "--")
    L.append(f"{lab} & {fmt(a2)} & {fmt(a3)} \\\\")
L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
open(f"{OUT}/tab_routing.tex", "w").write("\n".join(L) + "\n")

# ---------------- Table: accuracy inflation and tie rates
rp = rows("repro_tiedrop"); A = collections.defaultdict(list)
for c in rp:
    if c[1] in VLM:
        A[c[0]].append([float(c[3]), float(c[4]), float(c[5]), float(c[6]), float(c[8])])
L = ["% auto-generated by make_tables.py " + STAMP, "\\begin{table}[t]\\centering\\small", "\\setlength{\\tabcolsep}{3pt}",
     "\\caption{Dropping ties inflates reported accuracy, and judges almost never say `tie' (mean over VLM judges). "
     "Reported = forced choice on decided pairs only (the protocol of current benchmarks); all pairs = same choice, a human tie counts as an error; "
     "3-way = the judge may answer tie.}", "\\label{tab:inflation}", "\\begin{tabular}{lccccc}", "\\toprule",
     "Dataset & Human tie & Judge says tie & Reported acc. & All pairs & 3-way \\\\", "\\midrule"]
for ds in ["mtbench_human", "arena55k", "mllm_judge", "genai_arena/generation", "genai_arena/edition", "pickapic_u", "imagerewarddb"]:
    V = A.get(ds)
    if V:
        m = [mean([v[k] for v in V]) for k in range(5)]
        L.append(f"{NICE[ds]} & {m[0]:.2f} & {m[4]:.2f} & {m[1]:.2f} & {m[2]:.2f} & {m[3]:.2f} \\\\")
L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
open(f"{OUT}/tab_inflation.tex", "w").write("\n".join(L) + "\n")
print(OUT); [print(f) for f in sorted(os.listdir(OUT))]
